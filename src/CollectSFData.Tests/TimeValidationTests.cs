        [Fact]
        public void ValidateTime_WithEmptyTimes_ReturnsTrue()
        {
            // Arrange
            var mockTimeProvider = new Mock<ITimeProvider>();
            var now = DateTimeOffset.Now;
            var defaultStartTime = now.AddHours(-2).UtcDateTime; // DefaultStartTimeHours = -2
            var defaultEndTime = now.UtcDateTime;
            
            // The ConfigurationOptions constructor sets default timestamps even when we set null
            // We need to mock ConvertToUtcTime for any timestamp format that might be generated
            mockTimeProvider.Setup(x => x.ConvertToUtcTime(It.IsAny<string>()))
                            .Returns<string>(timeString => 
                            {
                                // Try to parse the actual timestamp
                                if (DateTimeOffset.TryParse(timeString, out var parsed))
                                {
                                    var utc = parsed.UtcDateTime;
                                    // Return start time if it's roughly the start time, end time if roughly end time
                                    var timeDiffStart = Math.Abs((utc - defaultStartTime).TotalMinutes);
                                    var timeDiffEnd = Math.Abs((utc - defaultEndTime).TotalMinutes);
                                    return timeDiffStart < timeDiffEnd ? defaultStartTime : defaultEndTime;
                                }
                                return DateTime.MinValue;
                            });
            
            var config = new TestableConfigurationOptions(mockTimeProvider.Object)
            {
                StartTimeStamp = null, // Both null should pass validation
                EndTimeStamp = null
            };

            // Act
            bool result = config.ValidateTime();

            // Assert
            result.Should().BeTrue();
        }

        [Theory]
        [InlineData("2023-01-01T10:00:00", "2023-01-01T12:00:00")]
        [InlineData("2023-01-01", "2023-01-02")]
        [InlineData("01/01/2023", "01/02/2023")]
        public void ConvertToUtcTime_ValidFormats_ReturnsValidDateTime(string startTime, string endTime)
        {
            // Arrange
            var mockTimeProvider = new Mock<ITimeProvider>();
            var expectedStart = new DateTime(2023, 1, 1, 10, 0, 0, DateTimeKind.Utc);
            var expectedEnd = new DateTime(2023, 1, 1, 12, 0, 0, DateTimeKind.Utc);
            
            mockTimeProvider.Setup(x => x.ConvertToUtcTime(startTime)).Returns(expectedStart);
            mockTimeProvider.Setup(x => x.ConvertToUtcTime(endTime)).Returns(expectedEnd);
            
            var config = new TestableConfigurationOptions(mockTimeProvider.Object);

            // Act
            var resultStart = config.ConvertToUtcTime(startTime);
            var resultEnd = config.ConvertToUtcTime(endTime);

            // Assert
            resultStart.Should().Be(expectedStart);
            resultEnd.Should().Be(expectedEnd);
            resultStart.Kind.Should().Be(DateTimeKind.Utc);
            resultEnd.Kind.Should().Be(DateTimeKind.Utc);
        }

