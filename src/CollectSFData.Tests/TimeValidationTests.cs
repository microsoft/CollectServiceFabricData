        [Fact]
        public void ValidateTime_WithValidTimeRange_ReturnsTrue()
        {
            // Arrange
            var mockTimeProvider = new Mock<ITimeProvider>();
            var startTime = new DateTime(2023, 1, 1, 10, 0, 0, DateTimeKind.Utc);
            var endTime = new DateTime(2023, 1, 1, 12, 0, 0, DateTimeKind.Utc);
            
            // Handle any timestamp format that might be generated by constructor or setters
            mockTimeProvider.Setup(x => x.ConvertToUtcTime(It.IsAny<string>()))
                            .Returns<string>(timeString => 
                            {
                                // For constructor-generated default times, return valid values
                                if (DateTimeOffset.TryParse(timeString, out var parsed))
                                {
                                    var utc = parsed.UtcDateTime;
                                    // Always ensure start time < end time
                                    // If it's the earlier time, it's the start; if later, it's the end
                                    if (timeString.Contains("2023-01-01T10:00:00"))
                                        return startTime;
                                    if (timeString.Contains("2023-01-01T12:00:00"))
                                        return endTime;
                                    
                                    // For default constructor times, make sure we return them in correct order
                                    var now = DateTimeOffset.Now.UtcDateTime;
                                    var defaultStart = now.AddHours(-2);
                                    var defaultEnd = now;
                                    
                                    // Return start time for anything that looks like it's in the past
                                    if (utc < now.AddHours(-1))
                                        return defaultStart;
                                    else
                                        return defaultEnd;
                                }
                                return DateTime.MinValue;
                            });
            
            var config = new TestableConfigurationOptions(mockTimeProvider.Object);
            
            // Set times (this will trigger ConvertToUtcTime calls)
            config.StartTimeStamp = "2023-01-01T10:00:00";
            config.EndTimeStamp = "2023-01-01T12:00:00";

            // Act
            bool result = config.ValidateTime();

            // Assert
            result.Should().BeTrue();
        }

